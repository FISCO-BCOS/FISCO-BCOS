struct GasCharacterizationV1Fixture
{
    std::shared_ptr<crypto::CryptoSuite> cryptoSuite = std::make_shared<crypto::CryptoSuite>(
        std::make_shared<crypto::Keccak256>(), nullptr, nullptr);
    bcostars::protocol::TransactionFactoryImpl transactionFactory{cryptoSuite};
    bcostars::protocol::TransactionReceiptFactoryImpl receiptFactory{cryptoSuite};
    PrecompiledManager precompiledManager{cryptoSuite->hashImpl()};
    TransactionExecutorImpl executor{receiptFactory, cryptoSuite->hashImpl(), precompiledManager};
    evmc_address sender = unhexAddress("abcdef0123456789abcdef0123456789abcdef02");

    GasCharacterizationV1Fixture()
    {
        executor::GlobalHashImpl::g_hashImpl = std::make_shared<crypto::Keccak256>();
    }

    protocol::Transaction::Ptr transaction(
        Step const& step, Addresses const& addresses, int contextID)
    {
        protocol::Transaction::Ptr tx;
        if (step.accessListTx)
        {
            auto raw = fromHexWithPrefix(c_accessListTx);
            auto rawRef = ref(raw);
            rpc::Web3Transaction web3Tx{};
            codec::rlp::decode(rawRef, web3Tx);
            auto inner = std::make_shared<bcostars::Transaction>(web3Tx.takeToTarsTransaction());
            auto const txHash = web3Tx.txHash();
            inner->extraTransactionHash.assign(txHash.begin(), txHash.end());
            tx = std::make_shared<bcostars::protocol::TransactionImpl>(
                [inner]() { return inner.get(); });
        }
        else if (step.gasLimit > 0)
        {
            // version 1 carries the transaction's own gas limit
            tx = transactionFactory.createTransaction(1, resolve(step.target, addresses),
                step.input(addresses), std::to_string(contextID), 0, "", "", 0, std::string{},
                "0x0", "0x0", step.gasLimit, "0x0", "0x0");
        }
        else
        {
            tx = transactionFactory.createTransaction(0, resolve(step.target, addresses),
                step.input(addresses), std::to_string(contextID), 0, "", "", 0);
        }
        tx->forceSender(bytes(sender.bytes, sender.bytes + 20));
        return tx;
    }

    // Runs the script on a fresh chain. Each configuration gets its own block number: contract
    // addresses derive from (block, context, seq) and the process-wide executable cache is keyed
    // by address, so two configurations must never share an address.
    void run(Config const& config, protocol::BlockNumber blockNumber, Recorder& recorder)
    {
        bcostars::protocol::BlockHeaderImpl blockHeader;
        blockHeader.setVersion(static_cast<uint32_t>(config.version));
        blockHeader.setNumber(blockNumber);
        blockHeader.calculateHash(*cryptoSuite->hashImpl());

        ledger::LedgerConfig ledgerConfig;
        ledgerConfig.setFeatures(config.features);
        ledgerConfig.setGasLimit({c_chainGasLimit, 0});
        MutableStorage storage;
        Addresses addresses;
        std::vector<protocol::TransactionReceipt::Ptr> receipts;
        int contextID = 0;
        for (auto const& step : script())
        {
            if (step.lane == Step::Lane::v0)
            {
                continue;
            }
            auto tx = transaction(step, addresses, contextID);
            auto receipt = task::syncWait(executor.executeTransaction(
                storage, blockHeader, *tx, contextID++, ledgerConfig, false));
            if (!receipt->contractAddress().empty())
            {
                addresses.emplace(step.name, std::string(receipt->contractAddress()));
            }
            recorder.add(config.name, step.name,
                {.status = receipt->status(),
                    .gasUsed = static_cast<int64_t>(receipt->gasUsed()),
                    .digest = digest(receipt->output(), receipt->contractAddress())});
            receipts.push_back(std::move(receipt));
        }
        // the header's gasUsed: BaselineScheduler sums the block's receipts this way
        auto total = protocol::normalizeReceipts(receipts);
        recorder.add(config.name, "block",
            {.status = 0, .gasUsed = static_cast<int64_t>(total), .digest = ""});
    }
};

