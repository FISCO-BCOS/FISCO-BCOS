{
    // A fresh chain at the given block, with the sender funded for the value transfer.
    ExecutorSmokeEnv chain(Config const& config, protocol::BlockNumber number)
    {
        BOOST_REQUIRE(!config.features.get(Flag::feature_evm_address));
        auto env = buildExecutorWithFeatures(config.features);
        const auto senderTable = "/apps/" + std::string(c_sender);
        std::promise<bool> created;
        env.storage->asyncCreateTable(senderTable, "value",
            [&created](Error::UniquePtr&& error, std::optional<storage::Table>&& table) {
                created.set_value(!error && table.has_value());
            });
        BOOST_REQUIRE(created.get_future().get());
        std::promise<bool> funded;
        env.storage->asyncSetRow(senderTable, executor::ACCOUNT_BALANCE, storage::Entry("1000000"),
            [&funded](Error::UniquePtr&& error) { funded.set_value(!error); });
        BOOST_REQUIRE(funded.get_future().get());

        task::syncWait(ledger::writeToStorage(config.features, *env.storage, number));
        auto blockHeader = std::make_shared<bcostars::protocol::BlockHeaderImpl>();
        blockHeader->setNumber(number);
        blockHeader->setVersion(static_cast<uint32_t>(config.version));
        blockHeader->setParentInfo({.blockNumber = number - 1, .blockHash = h256(number - 1)});
        ledger->setBlockNumber(number - 1);
        blockHeader->calculateHash(*cryptoSuite->hashImpl());
        std::promise<void> next;
        env.executor->nextBlockHeader(0, blockHeader, [&next](Error::Ptr&& error) {
            BOOST_CHECK(!error);
            next.set_value();
        });
        next.get_future().get();
        return env;
    }

    // the message BlockExecutive::buildMessage hands the executor for a transaction
    NativeExecutionMessage::UniquePtr message(Step const& step, Addresses const& addresses,
        int64_t contextID, protocol::BlockNumber number)
    {
        auto params = std::make_unique<NativeExecutionMessage>();
        params->setType(NativeExecutionMessage::MESSAGE);
        params->setContextID(contextID);
        params->setSeq(0);
        params->setDepth(0);
        params->setOrigin(std::string(c_sender));
        params->setFrom(std::string(c_sender));
        if (step.target.empty())
        {
            params->setCreate(true);
            params->setTo(newEVMAddress(hashImpl, number, contextID, 0));
        }
        else
        {
            params->setTo(resolve(step.target, addresses));
        }
        params->setStaticCall(false);
        params->setGasAvailable(c_chainGasLimit);
        params->setData(step.input(addresses));
        if (!step.value.empty())
        {
            params->setValue(step.value);
        }
        return params;
    }

    protocol::ExecutionMessage::UniquePtr serial(
        ExecutorSmokeEnv& env, NativeExecutionMessage::UniquePtr params)
    {
        std::vector<protocol::ExecutionMessage::UniquePtr> inputs;
        inputs.emplace_back(std::move(params));
        std::promise<std::vector<protocol::ExecutionMessage::UniquePtr>> promise;
        env.executor->executeTransactions(protocol::SERIAL_EXECUTIVE_FLOW_ADDRESS, inputs,
            [&promise](Error::UniquePtr error,
                std::vector<protocol::ExecutionMessage::UniquePtr> outputs) {
                BOOST_CHECK(!error);
                promise.set_value(std::move(outputs));
            });
        auto outputs = promise.get_future().get();
        BOOST_REQUIRE_EQUAL(outputs.size(), 1U);
        return std::move(outputs.front());
    }

    bytes code(ExecutorSmokeEnv& env, std::string_view address)
    {
        std::promise<bytes> promise;
        env.executor->getCode(address, [&promise](Error::Ptr error, bytes code) {
            BOOST_CHECK(!error);
            promise.set_value(std::move(code));
        });
        return promise.get_future().get();
    }

    // DmcExecutor's handling of one transaction's messages in miniature, both protocols: the
    // original (handleExecutiveMessage) and, under bugfix_dmc_revert, the one with PRE_FINISH
    // and a revert stack (handleExecutiveMessageV2). A MESSAGE out of the executor is a nested
    // frame, sent at the next seq (a creation gets its address first). Without PRE_FINISH a
    // FINISHED or REVERT pops the call stack and goes back to the caller's seq. With it a
    // finished child answers PRE_FINISH and stays open; when the transaction's frame finishes,
    // every open child gets a FINISHED to commit, and a REVERT reaching a frame with an open
    // child first goes to that child to roll it back. Every message goes out without key locks:
    // DmcExecutor sends the locks other contexts hold, and there is no other context here.
    protocol::ExecutionMessage::UniquePtr dmc(ExecutorSmokeEnv& env,
        NativeExecutionMessage::UniquePtr params, protocol::BlockNumber number, bool preFinish)
    {
        std::stack<int64_t> callStack;
        std::stack<std::pair<int64_t, std::string>> revertStack;
        callStack.push(0);
        if (preFinish)
        {
            revertStack.push({0, std::string(params->to())});
        }
        int64_t currentSeq = 1;
        protocol::ExecutionMessage::UniquePtr next = std::move(params);
        const auto sendToChild = [&revertStack](protocol::ExecutionMessage& message) {
            auto [seq, to] = revertStack.top();
            revertStack.pop();
            message.setSeq(seq);
            message.setFrom(std::string(message.to()));
            message.setTo(to);
            message.setCreate(false);
        };
        while (true)
        {
            next->setKeyLocks({});
            auto result = dmcExecute(
                *env.executor, std::unique_ptr<NativeExecutionMessage>(
                                   static_cast<NativeExecutionMessage*>(next.release())));
            switch (result->type())
            {
            case protocol::ExecutionMessage::MESSAGE:
                if (result->data().toBytes() == protocol::GET_CODE_INPUT_BYTES)
                {
                    // the frame asks for another contract's code (EIP-7702 resolution from
                    // Prague on); the scheduler answers on the frame's own seq
                    if (!preFinish)
                    {
                        ++currentSeq;
                    }
                    result->setData(code(env, result->delegateCallAddress()));
                    result->setType(preFinish ? protocol::ExecutionMessage::PRE_FINISH :
                                                protocol::ExecutionMessage::FINISHED);
                    result->setSeq(callStack.top());
                    result->setCreate(false);
                    break;
                }
                // not implemented here: CREATE2 addresses and delegate-call code fetches
                BOOST_REQUIRE(!result->createSalt() && !result->delegateCall());
                if (result->to().empty())
                {
                    result->setTo(newEVMAddress(hashImpl, number, result->contextID(), currentSeq));
                }
                callStack.push(currentSeq);
                if (preFinish)
                {
                    revertStack.push({currentSeq, std::string(result->to())});
                }
                result->setSeq(currentSeq++);
                break;
            case protocol::ExecutionMessage::PRE_FINISH:
                BOOST_REQUIRE(preFinish);
                callStack.pop();
                BOOST_REQUIRE(!callStack.empty());
                result->setSeq(callStack.top());
                result->setCreate(false);
                break;
            case protocol::ExecutionMessage::FINISHED:
                if (!preFinish)
                {
                    callStack.pop();
                    if (callStack.empty())
                    {
                        return result;
                    }
                    result->setSeq(callStack.top());
                    result->setCreate(false);
                    break;
                }
                if (revertStack.empty() || revertStack.top().first == 0)
                {
                    return result;
                }
                sendToChild(*result);
                break;
            case protocol::ExecutionMessage::REVERT:
                if (preFinish && !revertStack.empty())
                {
                    if (callStack.top() < revertStack.top().first)
                    {
                        sendToChild(*result);
                        break;
                    }
                    if (callStack.top() == revertStack.top().first)
                    {
                        revertStack.pop();
                    }
                }
                callStack.pop();
                if (callStack.empty())
                {
                    return result;
                }
                result->setSeq(callStack.top());
                result->setCreate(false);
                break;
            default:
                BOOST_FAIL("unexpected message type " << static_cast<int>(result->type()));
            }
            next = std::move(result);
        }
    }

    void run(Mode mode, Config const& config, protocol::BlockNumber number, Recorder& recorder)
    {
        auto env = chain(config, number);
        Addresses addresses;
        int64_t contextID = 0;
        for (auto const& step : script())
        {
            if (step.lane == Step::Lane::v1)
            {
                continue;
            }
            auto params = message(step, addresses, contextID++, number);
            auto result = mode == Mode::serial ? serial(env, std::move(params)) :
                                                 dmc(env, std::move(params), number,
                                                     config.features.get(Flag::bugfix_dmc_revert));
            auto const address = std::string(result->newEVMContractAddress());
            if (!address.empty())
            {
                addresses.emplace(step.name, address);
            }
            recorder.add(config.name, step.name,
                {.status = result->status(),
                    .gasUsed = c_chainGasLimit - result->gasAvailable(),
                    .digest = digest(result->data(), address)});
        }
    }

    void runAll(Mode mode, protocol::BlockNumber number, Recorder& recorder)
    {
        for (auto const& config : configs(c_flags, c_olderVersions))
        {
            // With feature_evm_prague on and bugfix_evm_create2_delegatecall_staticcall_codecopy
            // off, evmone's EIP-7702 check on every CALL/STATICCALL hands copyCode an
            // uninitialized 23-byte buffer, and the old copyCode branch (EVMHostInterface.cpp)
            // stores that buffer as the calling contract's code. Under DMC the next call into
            // the contract runs it, so the status changes from run to run. Serial execution
            // reads the original code hash from a block-level cache until the block ends, so
            // the serial table keeps these configurations: the script runs in one block.
            if (mode == Mode::dmc && config.features.get(Flag::feature_evm_prague) &&
                !config.features.get(Flag::bugfix_evm_create2_delegatecall_staticcall_codecopy))
            {
                ++number;
                continue;
            }
            run(mode, config, number++, recorder);
        }
    }
};

